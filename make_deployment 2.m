% Build Network Functions
function G = make_complete(n)
G = ones(n) - eye(n);
end

function G = make_star(n)
e1  = zeros(n,1);  
e1(1) = 1;   
one = ones(n,1);                

G = e1*one' + one*e1' - 2*(e1*e1');
end

function G = make_ring(n,k)
S = circshift(eye(n), 1);    
G = zeros(n);
Sj = eye(n);
for j = 1:k
    Sj = Sj*S;               
    G = G + Sj + Sj';
end
end

function G = make_disk(P,r)
n = size(P, 1);
s = zeros(n,1);
for i = 1:n
    s(i,1) = P(i,1)^2+P(i,2)^2;
end
delta = s*ones(1,n)+ones(n,1)*(s')-2*P*(P');
G = double(delta <= r^2);
G(logical(eye(n))) = 0;
end


